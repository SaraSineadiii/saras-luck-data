/* Regenerate the offline fallback bundles (data.js + history.js) from the feed's data.json.
   Preserves the static game meta + tax tables from a base data.js and overlays the fresh
   dynamic feed values (freqs, tickets, specialBias, learner, jackpot/cash) onto each game.
   Usage: node makebundle.mjs <feed-data.json> <base-data.js> <asOf> <targetDir> [targetDir...]
   Each targetDir receives a data.js + history.js. */
import fs from 'fs';
const [feedPath, basePath, asOf, ...targets] = process.argv.slice(2);
const feed = JSON.parse(fs.readFileSync(feedPath, 'utf8'));
const win = {}; eval(fs.readFileSync(basePath, 'utf8').replace('window.LOTTO_DATA', 'win.LOTTO_DATA'));
const B = win.LOTTO_DATA;
B.asOf = asOf;
const DYN = ['draws','whiteFreq','ticketFusion','ticketEdge','ticketData','specialBias','learner','cashLumpSum','advertisedAnnuity','jackpotOutcome','dataThrough','historyDates'];
for (const [g, specialKey] of [['powerball','powerFreq'], ['lottoAmerica','starFreq']]) {
  const s = feed[g], d = B[g];
  for (const k of DYN) if (k in s) d[k] = s[k];
  d[specialKey] = s.specialFreq;                    // feed calls it specialFreq; app expects powerFreq/starFreq
}
const HIST = { powerball: feed.powerball.history, lottoAmerica: feed.lottoAmerica.history };
const HDATES = { powerball: feed.powerball.historyDates || [], lottoAmerica: feed.lottoAmerica.historyDates || [] };
const dataJs = `/* Sara's Luck data — auto-generated by makebundle.mjs on ${asOf}.\n`
  + `   Static game meta + tax tables preserved; dynamic feed values overlaid.\n`
  + `   Offline fallback only — the live GitHub feed overrides this when online. */\n`
  + `window.LOTTO_DATA = ${JSON.stringify(B, null, 2)};\n`;
const histJs = `/* regenerated from feed. row=[w1..w5 sorted, special]; dates parallel to rows */\nwindow.LOTTO_HISTORY=${JSON.stringify(HIST)};\nwindow.LOTTO_HISTORY_DATES=${JSON.stringify(HDATES)};\n`;
for (const t of targets) {
  fs.writeFileSync(t + '/data.js', dataJs);
  fs.writeFileSync(t + '/history.js', histJs);
  console.log('wrote', t + '/data.js  (' + (dataJs.length/1024).toFixed(0) + 'kb) + history.js');
}
